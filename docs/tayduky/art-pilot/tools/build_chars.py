"""Copy every traced character strip into tayduky/world/chars/ and write tayduky/world/chars.js:
name -> {src, frames:[[x,y,w,h]...], views} where views is 'd4' (front, front-side, back-side, back), 'v3' (front, side, back) or 'v1'.
Run after the tracers: python build_chars.py"""
import os, json, glob, shutil
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'src', 'chars'); OUTC = os.path.join(HERE, '..', 'out', 'chars')
DST = os.path.abspath(os.path.join(HERE, '..', '..', '..', '..', 'tayduky', 'world', 'chars'))
MONKEY_LEFT = {'khi_chien_binh', 'khi_lao', 'khi_luc_si', 'khi_con', 'khi_giao'}


def frames_of(strip):
    a = strip.split()[3]; W, H = strip.size
    cols = [any(a.getpixel((x, y)) for y in range(H)) for x in range(W)]
    segs, s = [], None
    for x, c in enumerate(cols + [False]):
        if c and s is None: s = x
        if not c and s is not None: segs.append((s, x)); s = None
    out = []
    for (x0, x1) in segs:
        bb = strip.crop((x0, 0, x1, H)).getbbox(); out.append([x0 + bb[0], bb[1], bb[2] - bb[0], bb[3] - bb[1]])
    return out


if __name__ == '__main__':
    os.makedirs(DST, exist_ok=True); man = {}
    for js in sorted(glob.glob(os.path.join(SRC, '*.json'))):
        n = os.path.basename(js)[:-5]; png = os.path.join(OUTC, n + '.png')
        if not os.path.exists(png): continue
        src = json.load(open(js, encoding='utf-8')); k = len(src['frames'])
        strip = Image.open(png).convert('RGBA'); fr = frames_of(strip)
        if len(fr) != k: fr = fr[:k] if len(fr) > k else fr
        shutil.copy(png, os.path.join(DST, n + '.png'))
        man[n] = {'src': 'world/chars/%s.png' % n, 'frames': fr, 'views': 'd4' if k == 4 else 'v3' if k == 3 else 'v1', 'left': n in MONKEY_LEFT}
    with open(os.path.join(DST, '..', 'chars.js'), 'w', encoding='utf-8') as f:
        f.write('// generated by docs/tayduky/art-pilot/tools/build_chars.py\nwindow.TD_CHARS = ' + json.dumps(man) + ';\n')
    print(len(man), 'characters')
