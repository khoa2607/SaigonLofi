"""Tây Du Ký v2 — pack the PixelLab-generated object sprites into the runtime.

Inputs: tayduky/sprites/raw/<name>_<n>.png (the 128/160/170 px candidates downloaded from PixelLab's 1-direction object jobs).
Outputs: tayduky/sprites/<name>.png (trimmed to the opaque box, nothing resampled) and tayduky/sprites/sprites.js (manifest with the ground
anchor: py = rows from the top of the trimmed image to the footprint centre). Provenance lives in docs/tayduky/v2/PIXELLAB.md.
Run: python pack_sprites.py
"""
import os, json
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); RT = os.path.join(HERE, '..', '..', '..', '..', 'tayduky', 'sprites'); RAW = os.path.join(RT, 'raw')

# runtime name -> (raw file, anchor fraction of the opaque height that sits BELOW the footprint centre: half the base diamond's height)
PICK = {
    'hut_a': ('hut_0', 0.17), 'hut_b': ('hut_1', 0.17), 'hut_c': ('hut_3', 0.17),
    'shrine_a': ('shrine_0', 0.15), 'shrine_b': ('shrine_3', 0.15), 'shrine_c': ('shrine_1', 0.15),
    'stall_a': ('stall_0', 0.17), 'stall_b': ('stall_3', 0.17),
    'bridge_a': ('bridge_1', 0.2),
    'crystals_a': ('crystals_0', 0.2), 'crystals_b': ('crystals_1', 0.2), 'crystals_c': ('crystals_2', 0.2),
    'tent_a': ('tent_1', 0.16), 'tent_b': ('tent_3', 0.16), 'altar_a': ('altar_1', 0.17), 'altar_b': ('altar_3', 0.17),
    'silkbridge_a': ('silkbridge_1', 0.2),
}
EXTRA = json.load(open(os.path.join(HERE, 'sprite_picks.json'))) if os.path.exists(os.path.join(HERE, 'sprite_picks.json')) else {}
PICK.update({k: tuple(v) for k, v in EXTRA.items()})
man = {}
for name, (raw, f, *scale) in PICK.items():
    p = os.path.join(RAW, raw + '.png')
    if not os.path.exists(p): print('missing', raw); continue
    im = Image.open(p).convert('RGBA'); bb = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
    im = im.crop(bb)
    if scale:
        im = im.resize((im.width * scale[0], im.height * scale[0]), Image.Resampling.NEAREST)
    im.save(os.path.join(RT, name + '.png'))
    man[name] = {'w': im.width, 'h': im.height, 'py': round(im.height * (1 - f))}
with open(os.path.join(RT, 'sprites.js'), 'w', encoding='utf-8') as fh:
    fh.write('// generated by docs/tayduky/v2/tools/pack_sprites.py (PixelLab objects, see docs/tayduky/v2/PIXELLAB.md)\nwindow.TW_SPRITES = ' + json.dumps(man) + ';\n')
print(len(man), 'sprites')
